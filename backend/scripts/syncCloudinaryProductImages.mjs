import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';
import mongoose from 'mongoose';
import { v2 as cloudinary } from 'cloudinary';
import Product from '../models/productModel.js';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const backendDirectory = path.resolve(scriptDirectory, '..');
const repositoryRoot = path.resolve(backendDirectory, '..');
const assetFolder = 'loomora/products';
const productImagePattern = /^p_img(?:\d+|2_[1-4])\.png$/i;

dotenv.config({ path: path.join(backendDirectory, '.env') });

cloudinary.config({
    cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
    api_key: process.env.CLOUDINARY_API_KEY,
    api_secret: process.env.CLOUDINARY_API_SECRET
});

const hash = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');

const getTrackedProductImages = () => {
    const output = execFileSync(
        'git',
        ['ls-tree', '-r', '--name-only', 'HEAD', '--', 'frontend/src/assets/frontend_assets'],
        { cwd: repositoryRoot, encoding: 'utf8' }
    );

    return output
        .split(/\r?\n/)
        .filter(Boolean)
        .filter((file) => productImagePattern.test(path.basename(file)))
        .map((file) => ({
            file,
            name: path.parse(file).name,
            hash: hash(execFileSync('git', ['show', `HEAD:${file}`], { cwd: repositoryRoot }))
        }));
};

const getCloudinaryResources = async () => {
    const resources = [];
    let nextCursor;

    do {
        const result = await cloudinary.api.resources_by_asset_folder(assetFolder, {
            max_results: 500,
            next_cursor: nextCursor
        });
        resources.push(...result.resources);
        nextCursor = result.next_cursor;
    } while (nextCursor);

    return Promise.all(resources.map(async (resource) => {
        const response = await fetch(resource.secure_url);
        if (!response.ok) {
            throw new Error(`Could not download Cloudinary asset ${resource.public_id}`);
        }

        return {
            ...resource,
            hash: hash(Buffer.from(await response.arrayBuffer()))
        };
    }));
};

const createImageMap = (trackedImages, cloudinaryResources) => {
    const resourcesByHash = new Map();

    for (const resource of cloudinaryResources) {
        const matches = resourcesByHash.get(resource.hash) ?? [];
        matches.push(resource);
        resourcesByHash.set(resource.hash, matches);
    }

    return Object.fromEntries(trackedImages.map((image) => {
        const matches = resourcesByHash.get(image.hash);
        if (!matches?.length) {
            throw new Error(`No Cloudinary match found for ${image.file}`);
        }

        const resource = matches.shift();
        const optimizedUrl = resource.secure_url.replace('/upload/', '/upload/f_auto,q_auto/');
        return [image.name, optimizedUrl];
    }));
};

const writeGeneratedFiles = async (imageMap) => {
    const sortedEntries = Object.entries(imageMap).sort(([left], [right]) =>
        left.localeCompare(right, undefined, { numeric: true })
    );

    const frontendModule = [
        '// Generated by backend/scripts/syncCloudinaryProductImages.mjs',
        ...sortedEntries.map(([name, url]) => `export const ${name} = ${JSON.stringify(url)};`),
        ''
    ].join('\n');

    const frontendOutput = path.join(
        repositoryRoot,
        'frontend/src/assets/frontend_assets/productImages.js'
    );
    const backendDataDirectory = path.join(backendDirectory, 'data');
    const backendOutput = path.join(backendDataDirectory, 'cloudinaryProductImages.json');

    await fs.mkdir(backendDataDirectory, { recursive: true });
    await Promise.all([
        fs.writeFile(frontendOutput, frontendModule, 'utf8'),
        fs.writeFile(backendOutput, `${JSON.stringify(imageMap, null, 2)}\n`, 'utf8')
    ]);
};

const updateDatabase = async (imageMap) => {
    if (!process.argv.includes('--update-database')) {
        return 0;
    }

    await mongoose.connect(process.env.MONGODB_URI);
    const products = await Product.find({});
    let updatedProducts = 0;

    for (const product of products) {
        let changed = false;
        const nextImages = product.image.map((image) => {
            if (typeof image !== 'string' || !image.startsWith('/products/')) {
                return image;
            }

            const replacement = imageMap[path.parse(image).name];
            if (!replacement) {
                throw new Error(`No Cloudinary URL found for database image ${image}`);
            }

            changed = true;
            return replacement;
        });

        if (changed) {
            product.image = nextImages;
            await product.save();
            updatedProducts += 1;
        }
    }

    await mongoose.disconnect();
    return updatedProducts;
};

const main = async () => {
    const trackedImages = getTrackedProductImages();
    const cloudinaryResources = await getCloudinaryResources();

    if (trackedImages.length !== cloudinaryResources.length) {
        throw new Error(
            `Expected ${trackedImages.length} Cloudinary assets, found ${cloudinaryResources.length}`
        );
    }

    const imageMap = createImageMap(trackedImages, cloudinaryResources);
    await writeGeneratedFiles(imageMap);
    const updatedProducts = await updateDatabase(imageMap);

    console.log(`Mapped ${Object.keys(imageMap).length} product images to Cloudinary.`);
    console.log(`Updated ${updatedProducts} MongoDB product records.`);
};

main().catch(async (error) => {
    console.error('Cloudinary product image sync failed:', error.message);
    await mongoose.disconnect().catch(() => {});
    process.exitCode = 1;
});
